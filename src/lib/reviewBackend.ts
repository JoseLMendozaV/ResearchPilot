import { invoke } from "@tauri-apps/api/core";
import type { MasterField } from "../types";
import type {
  AuditEntry,
  CellInput,
  CellValue,
  ConflictInfo,
  ControlCoverage,
  Criterion,
  CriterionInput,
  Decision,
  DecisionInput,
  ExportRecord,
  ExportRequest,
  ExportResult,
  ExtractionMatrix,
  FieldInput,
  Phase,
  ProjectSettingsInput,
  ProjectWorkspace,
  ProtocolVersion,
  QualityCriterion,
  QualityCriterionInput,
  QualityTable,
  QuestionInput,
  QuestionsOverview,
  ScoreEntry,
  ScreeningRow,
  ScreeningTable,
  SearchStrategy,
  StrategyImportResult,
  StrategyInput,
} from "../reviewTypes";

export const reviewBackend = {
  workspace: (projectId: string) => invoke<ProjectWorkspace>("project_workspace", { projectId }),
  updateSettings: (input: ProjectSettingsInput) => invoke<ProjectWorkspace>("update_project_settings", { input }),
  addReviewer: (projectId: string, name: string, role: string) => invoke<ProjectWorkspace>("add_project_reviewer", { projectId, name, role }),
  setActiveReviewer: (projectId: string, reviewerId: string) => invoke<ProjectWorkspace>("set_active_reviewer", { projectId, reviewerId }),
  saveProtocol: (projectId: string, content: Record<string, unknown>, amendmentReason?: string) =>
    invoke<ProtocolVersion[]>("save_protocol", { projectId, content, amendmentReason }),
  approveProtocol: (projectId: string) => invoke<ProtocolVersion[]>("approve_protocol", { projectId }),
  addToCorpus: (projectId: string, articleIds: string[]) => invoke<number>("add_to_corpus", { projectId, articleIds }),
  setCorpusFlags: (projectId: string, articleId: string, isSecondary?: boolean, removed?: boolean) =>
    invoke<void>("set_corpus_flags", { projectId, articleId, isSecondary, removed }),
  controlCoverage: (projectId: string) => invoke<ControlCoverage>("control_coverage", { projectId }),
  addControl: (projectId: string, articleId: string, rationale: string) => invoke<ControlCoverage>("add_control_article", { projectId, articleId, rationale }),
  removeControl: (projectId: string, controlId: string) => invoke<ControlCoverage>("remove_control_article", { projectId, controlId }),
  questions: (projectId: string) => invoke<QuestionsOverview>("research_questions", { projectId }),
  saveQuestion: (input: QuestionInput) => invoke<QuestionsOverview>("save_research_question", { input }),
  deleteQuestion: (projectId: string, questionId: string) => invoke<QuestionsOverview>("delete_research_question", { projectId, questionId }),
  saveField: (input: FieldInput) => invoke<QuestionsOverview>("save_extraction_field", { input }),
  deleteField: (projectId: string, fieldId: string) => invoke<QuestionsOverview>("delete_extraction_field", { projectId, fieldId }),
  masterFields: () => invoke<MasterField[]>("list_master_fields"),
  strategies: (projectId: string) => invoke<SearchStrategy[]>("search_strategies", { projectId }),
  saveStrategy: (input: StrategyInput) => invoke<SearchStrategy[]>("save_search_strategy", { input }),
  deleteStrategy: (projectId: string, strategyId: string) => invoke<SearchStrategy[]>("delete_search_strategy", { projectId, strategyId }),
  importStrategyResults: (strategyId: string, path: string) => invoke<StrategyImportResult>("import_strategy_results", { strategyId, path }),
  criteria: (projectId: string) => invoke<Criterion[]>("eligibility_criteria", { projectId }),
  saveCriterion: (input: CriterionInput) => invoke<Criterion[]>("save_criterion", { input }),
  deleteCriterion: (projectId: string, criterionId: string) => invoke<Criterion[]>("delete_criterion", { projectId, criterionId }),
  screening: (projectId: string, phase: Phase) => invoke<ScreeningTable>("screening_table", { projectId, phase }),
  decide: (input: DecisionInput) => invoke<ScreeningRow>("record_screening_decision", { input }),
  resolveScreening: (conflictId: string, decision: Decision, criterionId: string | undefined, reason: string) =>
    invoke<ScreeningRow>("resolve_screening_conflict", { conflictId, decision, criterionId, reason }),
  conflicts: (projectId: string) => invoke<ConflictInfo[]>("review_conflicts", { projectId }),
  quality: (projectId: string) => invoke<QualityTable>("quality_table", { projectId }),
  saveQualityCriterion: (input: QualityCriterionInput) => invoke<QualityCriterion[]>("save_quality_criterion", { input }),
  deleteQualityCriterion: (projectId: string, criterionId: string) => invoke<QualityCriterion[]>("delete_quality_criterion", { projectId, criterionId }),
  saveScores: (projectId: string, articleId: string, scores: ScoreEntry[]) => invoke<QualityTable>("save_quality_scores", { projectId, articleId, scores }),
  resolveQuality: (conflictId: string, scores: ScoreEntry[], reason: string) => invoke<QualityTable>("resolve_quality_conflict", { conflictId, scores, reason }),
  matrix: (projectId: string, includeEligible: boolean) => invoke<ExtractionMatrix>("extraction_matrix", { projectId, includeEligible }),
  saveCell: (input: CellInput) => invoke<CellValue[]>("save_extraction_value", { input }),
  prefillMatrix: (projectId: string) => invoke<number>("prefill_matrix_from_master", { projectId }),
  audit: (projectId: string, limit = 300) => invoke<AuditEntry[]>("project_audit", { projectId, limit }),
  exportProject: (request: ExportRequest) => invoke<ExportResult>("export_project", { request }),
  exportHistory: (projectId: string) => invoke<ExportRecord[]>("export_history", { projectId }),
};
