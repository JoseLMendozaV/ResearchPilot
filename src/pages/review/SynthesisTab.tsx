import { useEffect, useState } from "react";
import { save } from "@tauri-apps/plugin-dialog";
import { AlertTriangle, Download, RefreshCw, Save } from "lucide-react";
import { BarChart, type BarDatum } from "../../components/BarChart";
import { formatDateTime } from "../../lib/extraction";
import { reviewBackend } from "../../lib/reviewBackend";
import type { Draft, DraftSection, Frequency } from "../../reviewTypes";
import { Card, ErrorNote, Loading, useAction, useLoad } from "./shared";

const sectionLabels: Record<DraftSection, string> = { methods: "Metodología", results: "Resultados", limitations: "Limitaciones" };
const toBars = (items: Frequency[]): BarDatum[] => items.map((item) => ({ label: item.value, value: item.count, detail: `Id ${item.studies.join(", ")}` }));

export function SynthesisTab({ projectId, projectName }: { projectId: string; projectName: string }) {
  const prisma = useLoad(() => Promise.all([reviewBackend.prismaCounts(projectId), reviewBackend.prismaSvg(projectId)]), [projectId]);
  const synthesis = useLoad(() => reviewBackend.synthesis(projectId), [projectId]);
  const action = useAction();
  const [notice, setNotice] = useState<string | null>(null);

  async function exportSvg() {
    const path = await save({ defaultPath: `PRISMA-${projectName.replace(/[^\p{L}\p{N}]+/gu, "-").slice(0, 50)}.svg`, filters: [{ name: "SVG", extensions: ["svg"] }] });
    if (!path) return;
    const result = await action.run(() => reviewBackend.exportProject({ projectId, format: "prisma", path }));
    if (result) setNotice(`${result.summary} · SHA-256 ${result.sha256.slice(0, 16)}…`);
  }

  const [counts, svg] = prisma.data ?? [null, ""];
  return (
    <div className="space-y-6">
      <Card title="Diagrama de flujo PRISMA 2020" actions={
        <>
          <button className="button-secondary px-3 py-2" onClick={() => void prisma.reload()}><RefreshCw className="size-3.5" /> Recalcular</button>
          <button className="button-primary px-3 py-2" disabled={!counts || action.busy} onClick={() => void exportSvg()}><Download className="size-3.5" /> Exportar SVG</button>
        </>
      }>
        {!counts ? (prisma.loading ? <Loading /> : <ErrorNote message={prisma.error} />) : (
          <div className="grid grid-cols-[1fr_280px] gap-6">
            {/* The SVG is generated by the Rust core with all text XML-escaped. */}
            <div className="overflow-auto rounded-xl border border-slate-100 bg-white p-2" dangerouslySetInnerHTML={{ __html: svg }} />
            <div className="space-y-3 text-[11px]">
              {!counts.complete && <p className="flex items-start gap-1.5 rounded-lg bg-amber-50 p-2.5 text-amber-900"><AlertTriangle className="mt-px size-3.5 shrink-0" /> Provisional: {counts.screeningPending} registro(s) sin decisión de cribado y {counts.fullTextPending} pendientes de texto completo.</p>}
              {counts.issues.map((issue) => <p key={issue} className="rounded-lg bg-rose-50 p-2.5 text-rose-800">{issue}</p>)}
              {counts.complete && counts.issues.length === 0 && <p className="rounded-lg bg-emerald-50 p-2.5 text-emerald-800">La contabilidad del flujo cuadra y no hay decisiones pendientes.</p>}
              <p className="leading-4 text-slate-500">Todos los números se calculan a partir de importaciones, el corpus y decisiones finales registradas. Los duplicados son registros que coincidieron con un estudio ya presente. Los motivos de exclusión provienen del criterio registrado en texto completo.</p>
              {counts.secondaryStudies > 0 && <p className="text-slate-500">{counts.secondaryStudies} estudio(s) marcados como secundarios siguen en el flujo y se listan aparte para trabajos relacionados.</p>}
              {notice && <p className="text-teal-700">{notice}</p>}
              <ErrorNote message={action.error} />
            </div>
          </div>
        )}
      </Card>

      <Card title={`Síntesis descriptiva${synthesis.data ? ` · ${synthesis.data.included} estudios incluidos` : ""}`}>
        {!synthesis.data ? (synthesis.loading ? <Loading /> : <ErrorNote message={synthesis.error} />) : (
          <div className="space-y-6">
            <div className="grid grid-cols-2 gap-6">
              <BarChart title="Estudios por año" data={toBars(synthesis.data.byYear)} />
              <BarChart title="Estudios por fuente" data={toBars(synthesis.data.bySource)} />
            </div>
            <p className="text-[11px] text-slate-400">Solo se usan valores confirmados de la matriz de extracción. Pasa el cursor o enfoca una barra para ver los Id de los estudios.</p>
            <div className="grid grid-cols-2 gap-6">
              {synthesis.data.fields.filter((field) => field.frequencies.length || field.numeric.length).map((field) => (
                <div key={field.fieldId} className="rounded-xl border border-slate-100 p-3">
                  {field.frequencies.length > 0 && <BarChart title={`${field.group} · ${field.name}`} data={toBars(field.frequencies)} />}
                  {field.numeric.map((group) => (
                    <div key={group.unit}>
                      <p className="text-xs font-semibold text-slate-700">{field.group} · {field.name}{group.unit ? ` (${group.unit})` : ""}</p>
                      <p className="mt-1 text-[11px] text-slate-600">n = {group.n} · mín. {group.min} · mediana {group.median} · máx. {group.max}</p>
                      <p className="text-[10px] text-slate-400">{group.values.map(([study, value]) => `Id ${study}: ${value}`).join(" · ")}</p>
                    </div>
                  ))}
                  <p className="mt-2 text-[10px] text-slate-400">{field.studiesWithData} de {synthesis.data!.included} estudios con dato confirmado</p>
                  {field.warnings.map((warning) => <p key={warning} className="mt-1 text-[10px] text-amber-700">{warning}</p>)}
                </div>
              ))}
            </div>
            {synthesis.data.fields.length === 0 && <p className="text-xs text-slate-400">Define aspectos en RQs y confirma valores en la matriz de extracción para ver su distribución.</p>}
          </div>
        )}
      </Card>

      <DraftsCard projectId={projectId} />
    </div>
  );
}

function DraftsCard({ projectId }: { projectId: string }) {
  const drafts = useLoad(() => reviewBackend.drafts(projectId), [projectId]);
  const action = useAction();
  const [editing, setEditing] = useState<Record<string, string>>({});
  const [confirming, setConfirming] = useState<DraftSection | null>(null);

  useEffect(() => {
    if (drafts.data) setEditing(Object.fromEntries(drafts.data.map((draft) => [draft.section, draft.content])));
  }, [drafts.data]);

  async function generate(section: DraftSection, existing?: Draft) {
    if (existing?.edited && confirming !== section) {
      setConfirming(section);
      return;
    }
    setConfirming(null);
    const next = await action.run(() => reviewBackend.generateDraft(projectId, section));
    if (next) drafts.setData(next);
  }

  async function saveSection(section: DraftSection) {
    const next = await action.run(() => reviewBackend.saveDraft(projectId, section, editing[section] ?? ""));
    if (next) drafts.setData(next);
  }

  return (
    <Card title="Borradores del informe">
      <p className="mb-4 text-[11px] leading-4 text-slate-500">Se generan solo a partir de datos registrados y valores confirmados; cada afirmación lleva los Id de los estudios que la sustentan. Son borradores para revisar y reescribir con tus palabras, no texto final.</p>
      <div className="space-y-4">
        {(Object.keys(sectionLabels) as DraftSection[]).map((section) => {
          const draft = drafts.data?.find((item) => item.section === section);
          return (
            <div key={section} className="rounded-xl border border-slate-100 p-3">
              <div className="flex items-center justify-between gap-2">
                <p className="text-xs font-semibold text-slate-700">{sectionLabels[section]}{draft?.edited ? <span className="ml-2 font-normal text-amber-700">editado</span> : null}</p>
                <div className="flex gap-1.5">
                  <button className="button-secondary px-2.5 py-1.5 text-[11px]" disabled={action.busy} onClick={() => void generate(section, draft)}><RefreshCw className="size-3" /> {draft ? "Regenerar" : "Generar"}</button>
                  {draft && <button className="button-primary px-2.5 py-1.5 text-[11px]" disabled={action.busy || editing[section] === draft.content} onClick={() => void saveSection(section)}><Save className="size-3" /> Guardar</button>}
                </div>
              </div>
              {confirming === section && (
                <p className="mt-2 rounded-lg bg-amber-50 px-3 py-2 text-[11px] text-amber-900">
                  El borrador tiene cambios tuyos. Regenerarlo los reemplaza (el texto anterior queda en la auditoría).
                  <button className="ml-2 font-semibold underline" onClick={() => void generate(section, draft)}>Regenerar igualmente</button>
                  <button className="ml-2 font-semibold underline" onClick={() => setConfirming(null)}>Cancelar</button>
                </p>
              )}
              {draft && (
                <>
                  <textarea className="input mt-2 min-h-48 font-mono text-[11px] leading-5" value={editing[section] ?? ""} onChange={(event) => setEditing({ ...editing, [section]: event.target.value })} aria-label={`Borrador de ${sectionLabels[section]}`} />
                  <p className="mt-1 text-[10px] text-slate-400">Generado {formatDateTime(draft.generatedAt)} · actualizado {formatDateTime(draft.updatedAt)}</p>
                </>
              )}
            </div>
          );
        })}
      </div>
      <div className="mt-3"><ErrorNote message={action.error} /></div>
    </Card>
  );
}
